
//Автомобиль — объект, содержащий в себе параметры «название» и «скорость».
public class Car {
    // на основе класса создаем объект, поля: наименование и скорость.
    String name;
    int speed;
// конструктор принимает 2 параметра
   Car(String name, int speed) {
    this.name = name;
    this.speed = speed;
}
}
